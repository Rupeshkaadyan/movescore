/**
 * PHASE 1-3 CITY SET — 30 major U.S. cities.
 *
 * Deliberately NOT 10,000 cities. These 30 are hand-curated so the calculation
 * engine can be excellent on a small surface before it is scaled out.
 *
 * DATA STATUS: every number below is a clearly-labelled DEMO value
 * (`DATA_STATUS = "demo"` in sources.ts). They are realistic in magnitude and
 * internally consistent, but they are not yet ingestion-backed and must not be
 * presented to users as verified data. See `docs/DATA.md` for the Phase 4 plan.
 */

type MetricsSeed = {
  pop: number;
  mhi: number;
  r1: number;
  r2: number;
  r3: number;
  home: number;
  propTax: number;
  rentGrowth: number;
  homeGrowth: number;
  col: number;
  rent: number;
  util: number;
  groc: number;
  trans: number;
  health: number;
  misc: number;
  unemp: number;
  jobGrowth: number;
  salaryIndex: number;
  industries: string[];
  /** Effective state income tax rate, as a percent. 0 for no-income-tax states. */
  stateTax: number;
  localTax?: number;
  salesTax: number;
  taxNote: string;
  commute: number;
  transit: number;
  walk: number;
  fare: number;
  climate: number;
  sunny: number;
  hi: number;
  lo: number;
  rain: number;
  aqi: number;
  hq: number;
  school: number;
  grad: number;
  bach: number;
  safety: number;
  violent: number;
  propertyCrime: number;
  amenity: number;
};

function m(s: MetricsSeed): CityMetrics {
  return {
    population: s.pop,
    medianHouseholdIncome: s.mhi,
    medianRent1br: s.r1,
    medianRent2br: s.r2,
    medianRent3br: s.r3,
    medianHomePrice: s.home,
    propertyTaxRate: s.propTax,
    rentGrowthYoY: s.rentGrowth,
    homeGrowthYoY: s.homeGrowth,
    colIndex: s.col,
    rentIndex: s.rent,
    utilitiesIndex: s.util,
    groceriesIndex: s.groc,
    transportationIndex: s.trans,
    healthcareIndex: s.health,
    miscIndex: s.misc,
    unemploymentRate: s.unemp,
    jobGrowthYoY: s.jobGrowth,
    salaryIndex: s.salaryIndex,
    topIndustries: s.industries,
    hasStateIncomeTax: s.stateTax > 0,
    stateIncomeTaxRate: s.stateTax,
    localIncomeTaxRate: s.localTax ?? 0,
    salesTaxRate: s.salesTax,
    stateTaxNote: s.taxNote,
    commuteMinutes: s.commute,
    transitScore: s.transit,
    walkScore: s.walk,
    transitFareMonthly: s.fare,
    climateScore: s.climate,
    sunnyDays: s.sunny,
    avgHighF: s.hi,
    avgLowF: s.lo,
    annualRainInches: s.rain,
    airQualityIndex: s.aqi,
    healthcareQualityIndex: s.hq,
    schoolScore: s.school,
    highSchoolGradRate: s.grad,
    bachelorShare: s.bach,
    safetyScore: s.safety,
    violentCrimePer100k: s.violent,
    propertyCrimePer100k: s.propertyCrime,
    amenityScore: s.amenity,
  };
}

